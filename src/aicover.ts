// "Generate cover with AI" on the Hide tab. It talks only to the local Vite dev server (server/ai-image.ts), which holds the
// API keys from .env. Only the picture's description is sent; the secret never is. The published site has no AI endpoint,
// so this is only switched on in development builds, and stays hidden unless a provider is configured.
const $ = <T extends HTMLElement>(id: string) => document.getElementById(id) as T;
const HEADERS = { 'x-veilvia-ai': '1' };

interface Provider {
  id: string;
  label: string;
  model: string;
}

export async function initAiCover(useCover: (blob: Blob, how: string) => Promise<boolean>, setStatus: (msg: string, error?: boolean) => void) {
  let providers: Provider[] = [];
  try {
    const res = await fetch('api/ai-image/providers', { headers: HEADERS });
    if (res.ok) providers = ((await res.json()) as { providers?: Provider[] }).providers ?? [];
  } catch {
    return;
  }
  if (!providers.length) return;
  const pick = $<HTMLSelectElement>('ai-provider');
  for (const p of providers) pick.append(new Option(`${p.label} (${p.model})`, p.id));
  pick.hidden = providers.length < 2;
  $('ai-provider-one').textContent = providers.length === 1 ? `Uses ${providers[0].label} (${providers[0].model}).` : '';
  $('ai-cover').hidden = false;
  const btn = $<HTMLButtonElement>('btn-ai-cover');
  const prompt = $<HTMLInputElement>('ai-prompt');
  btn.onclick = async () => {
    const text = prompt.value.trim() || prompt.placeholder;
    const who = providers.find((p) => p.id === pick.value) ?? providers[0];
    btn.disabled = true;
    const label = btn.textContent;
    btn.textContent = 'Generating…';
    setStatus(`Asking ${who.label} for a cover photo. This can take up to a minute…`);
    try {
      const res = await fetch('api/ai-image', {
        method: 'POST',
        headers: { ...HEADERS, 'Content-Type': 'application/json' },
        body: JSON.stringify({ provider: who.id, prompt: `${text}. A natural, detailed photograph with plenty of texture; no text, letters or logos.` }),
      });
      if (!res.ok) {
        const msg = ((await res.json().catch(() => ({}))) as { error?: string }).error;
        throw new Error(msg || `The AI request failed (HTTP ${res.status}).`);
      }
      if (await useCover(await res.blob(), `the image generated by ${who.label}`)) setStatus(`Cover photo generated by ${who.label}.`);
    } catch (e) {
      setStatus((e as Error).message || 'Could not reach the local AI endpoint. Is `npm run dev` running?', true);
    } finally {
      btn.disabled = false;
      btn.textContent = label;
    }
  };
}
